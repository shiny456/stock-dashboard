def page_statements():
    st.header("單元 8｜讀懂財報三表")
    st.markdown(
        """
總經告訴你『環境』，財報告訴你『這家公司在這個環境下賺不賺錢』。美國上市公司必須定期向 SEC 申報：
**10-K（年報）**、**10-Q（季報）**、**8-K（重大事件）**，都能在 [SEC EDGAR](https://www.sec.gov/edgar) 免費查到；
公司的投資人關係 (IR) 網站也有簡報與**財報電話會議 (earnings call)** 逐字稿。

### 三張表各回答一個問題
| 報表 | 回答的問題 | 時間性 |
|---|---|---|
| **損益表** | 這段期間賺了多少？ | 一段期間（流量） |
| **資產負債表** | 此刻有什麼、欠什麼？ | 某一個時點（存量） |
| **現金流量表** | 錢實際進出多少？ | 一段期間（流量） |

**損益表的順序**：營收 → (− 銷貨成本) **毛利** → (− 營業費用：研發、銷售管理) **營業利益** → (− 利息、稅) **淨利** → ÷ 流通股數 = **EPS**

**資產負債表恆等式**：資產 = 負債 + 股東權益

**現金流量表三段**：營業活動現金流 (CFO)、投資活動（含資本支出 CapEx）、融資活動（借款、還款、配息、回購）
**自由現金流 FCF = 營業現金流 − 資本支出**，是公司真正能自由運用、發給股東或再投資的錢。

### 三表怎麼連動？
淨利 → 累積到資產負債表的保留盈餘；損益表的淨利 + 折舊等非現金費用 ± 營運資金變動 → 營業現金流；
期末現金 → 回到資產負債表的現金。**看懂這條線，就能抓出『帳面賺錢、口袋沒錢』的公司。**
"""
    )

    st.subheader("🧮 互動：淨利 vs 現金流，差在哪？（金額單位：百萬美元）")
    c1, c2, c3 = st.columns(3)
    rev = c1.number_input("營收", 0, 100000, 1000, 50)
    cogs = c1.number_input("銷貨成本", 0, 100000, 600, 50)
    opex = c1.number_input("營業費用（含折舊）", 0, 100000, 250, 10)
    interest = c2.number_input("利息費用", 0, 10000, 20, 5)
    tax_rate = c2.slider("稅率 %", 0, 35, 21)
    dna = c2.number_input("折舊與攤銷（非現金費用）", 0, 10000, 50, 10)
    d_ar = c3.number_input("應收帳款增加", -1000, 10000, 80, 10, help="客戶賒帳、還沒收到的錢")
    d_inv = c3.number_input("存貨增加", -1000, 10000, 30, 10)
    d_ap = c3.number_input("應付帳款增加", -1000, 10000, 20, 10, help="你還沒付給供應商的錢")
    capex = c3.number_input("資本支出 CapEx", 0, 10000, 70, 10)

    gp = rev - cogs
    ebit = gp - opex
    pretax = ebit - interest
    ni = pretax - max(pretax, 0) * tax_rate / 100
    cfo = ni + dna - d_ar - d_inv + d_ap
    fcf = cfo - capex

    st.dataframe(
        pd.DataFrame(
            [("毛利", gp), ("營業利益 (EBIT)", ebit), ("淨利", ni), ("營業現金流 CFO", cfo), ("自由現金流 FCF", fcf)],
            columns=["項目", "百萬美元"],
        ).assign(百萬美元=lambda x: x["百萬美元"].round(1)),
        hide_index=True,
    )
    m = st.columns(3)
    m[0].metric("毛利率", _pct(gp / rev) if rev else "-")
    m[1].metric("淨利率", _pct(ni / rev) if rev else "-")
    m[2].metric("FCF ÷ 淨利", f"{fcf / ni:.0%}" if ni > 0 else "-")
    if ni > 0 and cfo < 0.7 * ni:
        st.warning("⚠️ 營業現金流遠低於淨利。常見原因：應收帳款或存貨暴增（賣了貨但沒收到錢／貨囤在倉庫）。"
                   "要追問：客戶付款變慢？是不是為了衝營收放寬信用條件？")
    elif ni > 0:
        st.success("現金流與淨利大致吻合，盈餘品質看起來不錯。")
    st.caption("試試把『應收帳款增加』調成 0，看看 FCF 怎麼變。")

    st.markdown(
        """
### 看財報時的三個提醒
- **GAAP vs 調整後 (non-GAAP)**：公司常公布『調整後』獲利，剔除重組費、**股票酬勞 (SBC)** 等項目。
  SBC 雖然不是現金支出，但會稀釋股東，應視為真實成本。
- **一次性項目**：出售資產的利得、訴訟和解等會讓單季獲利失真，要看『持續性營運』的數字。
- **看趨勢，不看單季**：至少看 3–5 年，並注意季節性（同季年增 YoY 比較）。

### 金融股要用不同尺
銀行、保險、REITs 的報表結構不同：銀行看淨利差 (NIM)、資本適足率、壞帳；REITs 看 FFO。
本課程的框架主要適用於一般產業（科技、消費、工業等）公司。
"""
    )
    takeaway("三表缺一不可：損益看賺多少、資產負債看家底、現金流看真金白銀",
             "FCF = 營業現金流 − 資本支出", "淨利遠高於現金流是紅旗，先查應收帳款與存貨")
    quiz("fs1", "一家公司淨利成長很快，但營業現金流持續下滑，最需要先檢查什麼？",
         ["股價走勢", "應收帳款與存貨的變化", "執行長學歷", "股息殖利率"], 1,
         "賺的是帳面獲利而沒有收到現金時，往往體現在應收帳款或存貨暴增。")
    quiz("fs2", "自由現金流 (FCF) 的常見算法是？",
         ["淨利 + 折舊", "營業現金流 − 資本支出", "營收 − 銷貨成本", "總資產 − 總負債"], 1, "FCF 是營運賺進的現金扣掉維持與擴張營運的資本支出。")


