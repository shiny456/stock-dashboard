def page_quality():
    st.header("單元 9｜獲利能力與盈餘品質")
    st.markdown(
        """
### 利潤率：每 1 塊錢營收留下多少
| 指標 | 公式 | 在看什麼 |
|---|---|---|
| 毛利率 | 毛利 ÷ 營收 | 產品本身的定價力與成本結構 |
| 營業利益率 | 營業利益 ÷ 營收 | 扣掉研發與管銷後的本業賺錢能力 |
| 淨利率 | 淨利 ÷ 營收 | 最終留給股東的比例 |

毛利率**不能跨產業比較**（軟體 70%+、零售 20–30% 都可能是正常的），要跟**自己的歷史**和**同業**比，看趨勢。

### 報酬率：公司用資本賺錢的效率
- **ROE** = 淨利 ÷ 平均股東權益
- **ROIC** = 稅後營業利益 (NOPAT) ÷ 投入資本；NOPAT = 營業利益 × (1 − 稅率)；投入資本 ≈ 有息負債 + 股東權益 − 多餘現金
- ROIC 要和**資本成本 (WACC)** 比：**ROIC > WACC 才是在創造價值**。

為什麼更看重 ROIC？因為 **ROE 可以被槓桿或回購灌水**。有些公司因長年大量回購，股東權益很小甚至為負，ROE 會失真。

### 杜邦分解：ROE 從哪來？
> **ROE = 淨利率 × 資產週轉率 × 權益乘數（財務槓桿）**
"""
    )

    st.subheader("🧮 互動：兩家 ROE 一樣的公司，品質一樣嗎？")
    ca, cb = st.columns(2)
    with ca:
        st.markdown("**公司 A**")
        a_m = st.slider("A 淨利率 %", 1.0, 40.0, 20.0, 0.5, key="a_m")
        a_t = st.slider("A 資產週轉率", 0.2, 3.0, 0.5, 0.05, key="a_t")
        a_l = st.slider("A 權益乘數", 1.0, 6.0, 1.5, 0.1, key="a_l")
    with cb:
        st.markdown("**公司 B**")
        b_m = st.slider("B 淨利率 %", 1.0, 40.0, 5.0, 0.5, key="b_m")
        b_t = st.slider("B 資產週轉率", 0.2, 3.0, 1.0, 0.05, key="b_t")
        b_l = st.slider("B 權益乘數", 1.0, 6.0, 3.0, 0.1, key="b_l")
    ra, rb = a_m * a_t * a_l, b_m * b_t * b_l
    m1, m2 = st.columns(2)
    m1.metric("A 的 ROE", f"{ra:.1f}%", f"槓桿貢獻：權益乘數 {a_l:.1f}x", delta_color="off")
    m2.metric("B 的 ROE", f"{rb:.1f}%", f"槓桿貢獻：權益乘數 {b_l:.1f}x", delta_color="off")
    st.caption("預設兩家 ROE 都是 15%：A 靠高利潤率、低槓桿；B 靠高槓桿。景氣轉差或利率升高時，B 的風險大很多。")

    st.subheader("🧮 互動：ROIC 有沒有超過資本成本？")
    c1, c2, c3, c4 = st.columns(4)
    ebit = c1.number_input("營業利益 EBIT（百萬）", 0.0, 100000.0, 300.0, 10.0)
    tax = c2.slider("稅率 %", 0, 35, 21, key="roic_tax")
    ic = c3.number_input("投入資本（百萬）", 1.0, 1000000.0, 2000.0, 100.0)
    wacc = c4.slider("資本成本 WACC %", 4.0, 15.0, 9.0, 0.5, help="利率上升時，WACC 也會跟著升高")
    roic = ebit * (1 - tax / 100) / ic * 100
    k1, k2 = st.columns(2)
    k1.metric("ROIC", f"{roic:.1f}%")
    k2.metric("ROIC − WACC", f"{roic - wacc:+.1f} 個百分點")
    if roic > wacc:
        st.success("ROIC 高於資本成本：每多投入一塊錢，創造的價值大於成本。")
    else:
        st.error("ROIC 低於資本成本：即使會計上有獲利，實質上在『毀滅價值』。")

    st.markdown(
        """
### 盈餘品質：獲利是『真的』嗎？
| 檢查 | 做法 | 紅旗 |
|---|---|---|
| **FCF 轉換率** | FCF ÷ 淨利，看連續數年 | 長期遠低於 70–100% |
| **應計項目比率** | (淨利 − 營業現金流) ÷ 平均總資產 | 持續為正且擴大（獲利靠會計而非現金） |
| **應收帳款天數** | 應收帳款 ÷ 營收 × 365 | 逐年拉長 |
| **存貨天數** | 存貨 ÷ 銷貨成本 × 365 | 逐年拉長（可能滯銷） |
| **SBC 占營收比** | 股票酬勞 ÷ 營收 | 很高，且 FCF 扣除 SBC 後就剩很少 |
| **調整後 vs GAAP 差距** | 兩者差距占比 | 差距逐年擴大 |
"""
    )
    takeaway("利潤率看趨勢與同業，不跨產業比", "ROIC > WACC 才創造價值；ROE 可能被槓桿灌水", "盈餘品質看現金流是否跟得上淨利")
    quiz("pq1", "兩家公司 ROE 都是 15%，A 的權益乘數 1.5、B 是 3.0。通常哪家的獲利品質較佳？",
         ["B，因為槓桿高", "A，因為不依賴高槓桿", "一樣", "無法比較"], 1, "ROE 靠高槓桿撐起來時，景氣與利率不利時脆弱得多。")
    quiz("pq2", "一家公司 ROIC 7%，資本成本 9%，這表示？",
         ["創造價值", "損益兩平", "在毀滅價值", "與價值無關"], 2, "報酬低於資金成本，成長越多反而越傷。")


