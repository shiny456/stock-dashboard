def page_growth_moat():
    st.header("單元 10｜成長與護城河")
    st.markdown(
        """
### 成長：要問『哪裡來』『能不能持續』
營收成長可以拆成：**量（賣更多）× 價（漲價）+ 併購 ± 匯率**。
- **有機成長 (organic)**：排除併購與匯率後的成長，最能反映本業。
- **成長品質**：靠漲價、新客戶，比靠大量促銷或收購買來的穩。
- **集中度風險**：前幾大客戶占營收比例太高時，一個客戶砍單就是大事。

### 營運槓桿：營收成長，利潤成長得更快
當公司有**固定成本**（廠房、研發團隊），營收增加時，利潤會成長得比營收更快——反過來衰退時也跌得更快。
"""
    )
    st.subheader("🧮 互動：營運槓桿")
    c1, c2, c3 = st.columns(3)
    var_ratio = c1.slider("變動成本占營收 %", 10, 90, 40)
    fixed = c2.slider("固定成本（營收=100 時）", 0, 80, 40)
    growth = c3.slider("營收成長 %", -30, 50, 10)
    oi0 = 100 * (1 - var_ratio / 100) - fixed
    rev1 = 100 * (1 + growth / 100)
    oi1 = rev1 * (1 - var_ratio / 100) - fixed
    if oi0 <= 0:
        st.error("基期就虧損，請調低固定成本或變動成本。")
    else:
        dol = (100 * (1 - var_ratio / 100)) / oi0
        m = st.columns(3)
        m[0].metric("基期營業利益", f"{oi0:.1f}")
        m[1].metric("營業利益變動", f"{(oi1 / oi0 - 1) * 100:+.0f}%")
        m[2].metric("營運槓桿倍數 (DOL)", f"{dol:.1f}x")
        st.caption("營運槓桿倍數 = 貢獻邊際 ÷ 營業利益。固定成本越高，倍數越大，景氣循環中利潤波動也越劇烈。")

    st.markdown(
        """
### 護城河 (Economic Moat)：憑什麼長期賺高於平均的報酬？
| 類型 | 白話 | 觀念舉例（非推薦） |
|---|---|---|
| **無形資產** | 品牌、專利、執照讓對手難複製 | 知名品牌、藥廠專利、交易所執照 |
| **轉換成本** | 客戶換掉你的痛苦大於好處 | 企業軟體、開發者生態系（如輝達的 CUDA） |
| **網路效應** | 用的人越多，價值越高 | 信用卡支付網路、社群平台 |
| **成本優勢／規模** | 規模大、成本低，對手打不過 | 大型連鎖量販、先進製程龍頭 |
| **有效規模** | 小市場只容得下一兩家 | 區域型管線、機場 |

### 怎麼從財報驗證護城河？
護城河不是說出來的，會**反映在數字上**：
1. **ROIC 長期明顯高於資本成本**（常見經驗門檻：持續 > 10–15%）
2. **毛利率穩定或上升**，不需靠降價搶單
3. **定價能力**：能漲價而不流失客戶（看通膨期的毛利率表現）
4. **市占率**穩定或上升

### 護城河會變窄
技術顛覆（柯達被數位相機取代）、法規改變、管理層失誤，都可能讓護城河消失。
所以要回頭問：**『我的買入理由還成立嗎？』**——這就是**基本面停損**的概念：只要護城河、財務體質、長期劇本沒變，就不被短期股價波動洗出場；一旦理由改變，要有紀律地處理。
"""
    )
    takeaway("成長要拆來源與持續性，優先看有機成長", "固定成本高 → 營運槓桿大 → 利潤波動大",
             "護城河要用長期 ROIC、毛利率、定價能力來驗證")
    quiz("gm1", "一家公司宣稱有很深的護城河，但長期 ROIC 只有 5%、低於資本成本，你應該？",
         ["相信公司說法", "質疑護城河是否真實", "只看股價", "忽略財報"], 1, "真正的護城河會反映在長期高於資本成本的報酬上。")
    quiz("gm2", "固定成本占比高的公司，營收下滑時，利潤通常會？",
         ["跌得比營收少", "跌得比營收多", "完全不變", "反而上升"], 1, "營運槓桿是雙面刃，固定成本攤不掉，利潤下滑更快。")


