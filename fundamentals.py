def page_health():
    st.header("單元 11｜財務體質與利率風險")
    st.markdown(
        """
利率高的時候，『活得久』比『賺得多』更重要。

### 常用體質指標
| 指標 | 公式 | 怎麼看 |
|---|---|---|
| 流動比率 | 流動資產 ÷ 流動負債 | 短期償債能力；與產業相關，一般高於 1 較穩 |
| 淨負債 | 有息負債 − 現金 | 負數代表淨現金 |
| 淨負債 / EBITDA | 淨負債 ÷ EBITDA | 還清債務大約需要幾年的獲利；經驗上 < 2–3 倍較安全（因產業而異） |
| 利息保障倍數 | EBIT ÷ 利息費用 | 賺的錢是利息的幾倍；低於約 3 倍需留意，低於 1.5 倍風險高 |
| 負債權益比 | 總負債 ÷ 股東權益 | 槓桿程度；不同產業標準差異大 |

### 其他要看的地方
- **債務到期結構**：未來 1–3 年有多少債務要到期？低利時期發的債，要用更高利率換新（**再融資風險**）。
- **浮動利率債務比例**：浮動利率會馬上反映升息。
- **現金跑道 (cash runway)**：尚未獲利的成長公司，現金 ÷ 每年燒錢速度 = 還能撐多久。
- **稀釋**：燒完現金後靠增資、可轉債過活，會稀釋現有股東。
"""
    )

    st.subheader("🧮 互動：利率上升，利息保障倍數會掉多少？")
    c1, c2, c3 = st.columns(3)
    debt = c1.number_input("有息負債總額（百萬）", 0, 1000000, 2000, 100)
    ebit = c1.number_input("營業利益 EBIT（百萬）", 0, 1000000, 300, 10)
    c0 = c2.slider("目前平均利率 %", 0.5, 10.0, 3.5, 0.25)
    rn = c2.slider("未來新借／再融資利率 %", 1.0, 12.0, 6.0, 0.25)
    f = c3.slider("2 年內需再融資或屬浮動利率的比例 %", 0, 100, 40, 5)
    before = debt * c0 / 100
    after = debt * ((1 - f / 100) * c0 + f / 100 * rn) / 100
    cov0 = ebit / before if before else float("inf")
    cov1 = ebit / after if after else float("inf")
    m = st.columns(3)
    m[0].metric("利息費用", f"{after:.0f}", f"{after - before:+.0f}（原 {before:.0f}）", delta_color="inverse")
    m[1].metric("利息保障倍數（現在）", f"{cov0:.1f}x")
    m[2].metric("利息保障倍數（再融資後）", f"{cov1:.1f}x", f"{cov1 - cov0:+.1f}x", delta_color="inverse")
    if cov1 < 1.5:
        st.error("利息保障倍數低於 1.5：獲利幾乎被利息吃光，景氣稍差就可能出問題。")
    elif cov1 < 3:
        st.warning("利息保障倍數偏低，需留意。")
    else:
        st.success("利息保障倍數仍有餘裕。")

    st.subheader("🧮 互動：現金還能撐多久？")
    k1, k2 = st.columns(2)
    cash = k1.number_input("現金與短期投資（百萬）", 0, 1000000, 800, 50)
    burn = k2.number_input("每年自由現金流為負的金額（百萬）", 1, 1000000, 400, 50)
    st.metric("現金跑道", f"約 {cash / burn * 12:.0f} 個月")
    st.caption("跑道少於 18–24 個月且沒有獲利路徑的公司，要預期增資或舉債，對現有股東是稀釋風險。")

    takeaway("利率高時，先看會不會『活不下去』，再看賺得多不多", "再融資與浮動利率債務是升息的傳導管道",
             "金融股另有一套指標，別硬套")
    quiz("hl1", "利息保障倍數 = ？",
         ["淨利 ÷ 利息", "EBIT ÷ 利息費用", "營收 ÷ 利息", "現金 ÷ 利息"], 1, "代表營業利益是利息費用的幾倍。")
    quiz("hl2", "公司 40% 債務將在兩年內以更高利率再融資，最直接的影響是？",
         ["營收增加", "利息費用上升、利息保障倍數下降", "毛利率上升", "存貨減少"], 1, "利息成本上升，吃掉營業利益。")


