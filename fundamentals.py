def dcf_per_share(fcf0, g1, years, gT, r, net_debt, shares):
    if r <= gT:
        return None, None
    pv = 0.0
    fcf = fcf0
    for t in range(1, years + 1):
        fcf *= 1 + g1
        pv += fcf / (1 + r) ** t
    tv = fcf * (1 + gT) / (r - gT)
    pv_tv = tv / (1 + r) ** years
    ev = pv + pv_tv
    return (ev - net_debt) / shares, pv_tv / ev


def page_valuation():
    st.header("單元 12｜估值：好公司也有價格")
    st.markdown(
        """
好公司 ≠ 好投資。**價格決定報酬**：用太貴的價格買好公司，報酬可能很差；便宜也要有理由站得住腳。

### 常用估值倍數
| 指標 | 公式 | 適合 / 注意 |
|---|---|---|
| **P/E** | 股價 ÷ EPS | 最常用。景氣循環股在獲利高峰時 P/E 很低反而是陷阱 |
| **PEG** | P/E ÷ 預期 EPS 年成長率(%) | 粗略調整成長；成長預測不準時意義有限 |
| **P/S** | 市值 ÷ 營收 | 尚未獲利的成長股；要搭配利潤率看 |
| **P/B** | 市值 ÷ 帳面淨值 | 銀行等金融股 |
| **EV/EBITDA** | (市值 + 淨負債) ÷ EBITDA | 跨資本結構比較；忽略資本支出，重資產行業要小心 |
| **FCF 殖利率** | FCF ÷ 市值 | 直接和公債殖利率比較（呼應單元 4） |

**EV (企業價值)** = 市值 + 淨負債（含少數股權、優先股）。意思是『把整家公司買下來』要付的價錢。

### 倍數的三個陷阱
1. **便宜有理由**（價值陷阱）：獲利要衰退、護城河在變窄。
2. **貴也可能有理由**：高成長、高 ROIC、現金流持續擴張。
3. **跨產業比較無意義**：軟體與銀行的合理倍數天差地遠。

### DCF：把未來現金流折現（連結單元 1）
> **公司價值 = 未來每年 FCF 的現值總和 + 終值的現值**
"""
    )

    st.subheader("🧮 互動：簡易兩階段 DCF")
    c1, c2, c3 = st.columns(3)
    fcf0 = c1.number_input("今年 FCF（百萬）", 1.0, 1000000.0, 100.0, 10.0)
    g1 = c1.slider("未來 5 年 FCF 年成長率 %", -5.0, 40.0, 10.0, 0.5)
    gT = c2.slider("5 年後長期成長率 %", 0.0, 5.0, 3.0, 0.25, help="長期不應高於名目 GDP 成長")
    rf = c2.slider("無風險利率（約等於 10Y）%", 0.5, 8.0, 5.0, 0.1)
    erp = c3.slider("要求的風險溢價 %", 2.0, 8.0, 4.5, 0.25)
    net_debt = c3.number_input("淨負債（百萬，淨現金填負數）", -1000000.0, 1000000.0, 200.0, 50.0)
    shares = c3.number_input("流通股數（百萬股）", 1.0, 1000000.0, 50.0, 5.0)
    price = c1.number_input("目前股價", 0.1, 100000.0, 35.0, 1.0)
    r = (rf + erp) / 100
    c2.metric("折現率 r = 無風險 + 風險溢價", f"{r * 100:.2f}%")
    val, tv_share = dcf_per_share(fcf0, g1 / 100, 5, gT / 100, r, net_debt, shares)
    if val is None:
        st.error("折現率必須大於長期成長率。")
    else:
        m = st.columns(3)
        m[0].metric("DCF 每股內在價值（估）", f"{val:.1f}")
        m[1].metric("相對現價的空間", f"{(val / price - 1) * 100:+.0f}%", f"現價 {price:.1f}", delta_color="off")
        m[2].metric("終值占總價值", f"{tv_share * 100:.0f}%")
        st.caption("終值占比通常很高，代表估值非常依賴『長期成長率』與『折現率』這兩個最難預測的數字。")

        st.markdown("**敏感度表：折現率 × 長期成長率 → 每股價值**")
        rs = [r + d / 100 for d in (-2, -1, 0, 1, 2)]
        gs = [2.0, 2.5, 3.0, 3.5, 4.0]
        table = pd.DataFrame(
            {f"g={g}%": [(dcf_per_share(fcf0, g1 / 100, 5, g / 100, rr, net_debt, shares)[0]) for rr in rs] for g in gs},
            index=[f"r={rr * 100:.1f}%" for rr in rs],
        )
        st.dataframe(table.round(1))
        st.caption("把無風險利率從 4% 調到 5%，看每一格的價值掉多少——這就是『利率上升壓縮估值』的量化版（尤其對成長股）。")

    st.markdown(
        """
### 反過來用：反推市場在假設什麼（Reverse DCF）
與其猜『合理價值』，不如把現價代進去，問：**市場要求這家公司未來成長多少，才合理？**
如果需要的成長率遠高於它的歷史水準，代表市場已經把樂觀情境都算進價格裡。

### 安全邊際 (Margin of Safety)
估值一定有誤差，所以只在**價格明顯低於你估計的價值**時才有足夠的容錯空間。
"""
    )
    takeaway("好公司 ≠ 好價格；倍數要跟自己的歷史、同業、成長與利率環境比",
             "DCF 對折現率與終值極度敏感，只能當範圍，不是精準答案", "利率上升 → 折現率上升 → 同樣的未來現金流現值變小")
